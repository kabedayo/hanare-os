#!/usr/bin/env bash
# HANARE service unit generator: builds systemd user units from the
# single service registry (services/services.tsv).
#
#   hanare-service-gen.sh [service-name]
#
# For every registry row whose exec column is not "-", a unit file
#   $HANARE_UNIT_DIR/<unit>.service     (default ~/.config/systemd/user)
# is (re)written from the registry row, then `systemctl --user
# daemon-reload` runs once. Rows with exec "-" are hand-managed units
# (their unit files live in systemd/ and are installed by
# setup/13-install-services.sh); they are never generated or touched.
#
# Env: HANARE_SERVICES_TSV  registry path override
#      HANARE_UNIT_DIR      unit output dir override (tests)
#      HANARE_SYSTEMCTL     systemctl binary override (tests)
#      HANARE_NO_RELOAD=1   skip daemon-reload
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
TSV="${HANARE_SERVICES_TSV:-$REPO_ROOT/services/services.tsv}"
UNIT_DIR="${HANARE_UNIT_DIR:-$HOME/.config/systemd/user}"
SYSTEMCTL="${HANARE_SYSTEMCTL:-systemctl}"
ONLY="${1:-}"

trim() {
  local s=$1
  s=${s#"${s%%[![:space:]]*}"}
  s=${s%"${s##*[![:space:]]}"}
  printf '%s' "$s"
}

[ -r "$TSV" ] || { echo "hanare-service-gen: registry not found: $TSV" >&2; exit 1; }
mkdir -p "$UNIT_DIR" || exit 1

generated=0
skipped=0
while IFS=$'\t' read -r name port kw display unit exec workdir url; do
  name="$(trim "$name")"
  case "$name" in ''|'#'*) continue ;; esac
  [ -n "$ONLY" ] && [ "$name" != "$ONLY" ] && continue
  unit="$(trim "${unit:-}")"
  exec="$(trim "${exec:-}")"
  display="$(trim "${display:-}")"
  workdir="$(trim "${workdir:-}")"
  if [ -z "$exec" ] || [ "$exec" = "-" ]; then
    skipped=$((skipped + 1))
    continue
  fi
  if [ -z "$unit" ]; then
    echo "hanare-service-gen: $name: exec is set but unit column is empty; skipped" >&2
    skipped=$((skipped + 1))
    continue
  fi
  case "$unit" in *[!A-Za-z0-9_@.-]*)
    echo "hanare-service-gen: $name: unsafe unit name: $unit" >&2
    exit 1
    ;;
  esac
  [ "$workdir" = "-" ] && workdir=""
  [ -z "$display" ] && display="$name"
  out="$UNIT_DIR/$unit.service"
  {
    printf '# Generated by scripts/hanare-service-gen.sh from services/services.tsv.\n'
    printf '# Edit the registry row, not this file.\n'
    printf '[Unit]\n'
    printf 'Description=HANARE %s (registry service %s, 127.0.0.1:%s)\n' "$display" "$name" "${port:-?}"
    printf 'After=network.target\n'
    printf '\n'
    printf '[Service]\n'
    printf 'ExecStart=%s\n' "$exec"
    if [ -n "$workdir" ]; then
      printf 'WorkingDirectory=%s\n' "$workdir"
    fi
    printf 'Restart=on-failure\n'
    printf 'RestartSec=10s\n'
    printf 'TimeoutStopSec=60\n'
    printf '\n'
    printf '# No [Install] section on purpose: started/stopped on demand from the HANARE UIs.\n'
  } > "$out.tmp" || exit 1
  mv "$out.tmp" "$out" || exit 1
  echo "generated: $out"
  generated=$((generated + 1))
done < "$TSV"

if [ -n "$ONLY" ] && [ "$generated" -eq 0 ] && [ "$skipped" -eq 0 ]; then
  echo "hanare-service-gen: unknown service: $ONLY" >&2
  exit 2
fi

if [ "${HANARE_NO_RELOAD:-}" != "1" ]; then
  "$SYSTEMCTL" --user daemon-reload 2>/dev/null || \
    echo "note: systemctl --user daemon-reload failed (no user bus?); units are written" >&2
fi
echo "hanare-service-gen: $generated generated, $skipped hand-managed/skipped"
exit 0
